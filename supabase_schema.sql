-- StandOut Supabase Schema
-- Run this in the Supabase SQL Editor (https://supabase.com/dashboard/project/_/sql)

-- 1. Create table for storing published portfolios
CREATE TABLE IF NOT EXISTS public.published_portfolios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug TEXT UNIQUE NOT NULL,
    username TEXT,
    portfolio_data JSONB NOT NULL,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 2. Create index on slug for fast lookup
CREATE INDEX IF NOT EXISTS idx_published_portfolios_slug ON public.published_portfolios(slug);

-- 3. Enable Row Level Security (RLS)
ALTER TABLE public.published_portfolios ENABLE ROW LEVEL SECURITY;

-- 4. Allow public anonymous read access (anyone with the link can view the portfolio)
CREATE POLICY "Allow public read access to published portfolios"
    ON public.published_portfolios
    FOR SELECT
    USING (true);

-- 5. Allow anonymous insert and update (users can publish and update their portfolio)
CREATE POLICY "Allow public insert to published portfolios"
    ON public.published_portfolios
    FOR INSERT
    WITH CHECK (true);

CREATE POLICY "Allow public update to published portfolios"
    ON public.published_portfolios
    FOR UPDATE
    USING (true)
    WITH CHECK (true);
